/** Множення многочленів (коефіцієнти від старшого до молодшого). */
function mul(a: number[], b: number[]): number[] {
  const r = Array(a.length + b.length - 1).fill(0) as number[]
  a.forEach((x, i) => b.forEach((y, j) => (r[i + j] += x * y)))
  return r
}
/** Значення многочлена за схемою Горнера. */
const evalP = (c: number[], x: number): number => c.reduce((s, v) => s * x + v, 0)
/** Рядок схеми Горнера для кореня a. Останнє число — остача. */
function hornerRow(c: number[], a: number): number[] {
  const out = [c[0]]
  for (let i = 1; i < c.length; i++) out.push(c[i] + a * out[i - 1])
  return out
}
const rowTex = (r: number[]) => r.map((v) => num(v)).join(';\\ ')
const setTex = (vals: number[]) => (vals.length ? `\\{${vals.map((v) => num(v)).join(';\\, ')}\\}` : '\\varnothing')
const uniqSorted = (vals: number[]) => [...new Set(vals)].sort((a, b) => a - b)
const ROOTS_HINT = 'Введи корені через «;». Якщо коренів немає, напиши «немає».'

/** Многочлен у вигляді ∏(x − r). */
const fromRoots = (roots: number[]): number[] => roots.reduce((acc, r) => mul(acc, [1, -r]), [1])

/** Випадковий многочлен степеня deg зі старшим коефіцієнтом lead. */
function randPoly(rng: Rng, deg: number, lead: number, lim = 5): number[] {
  const c = [lead]
  for (let i = 0; i < deg; i++) c.push(rng.nonZero(-lim, lim))
  return c
}

